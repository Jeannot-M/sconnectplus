<h4>Cookies</h4>
<h4>Votre vie privée est précieuse, protégeons-là ensemble</h4>
<p>Chez Sconnect Plus, notre volonté est de vous faire bénéficier de la meilleure expérience possible à chaque instant. Lorsque vous vous connectez sur notre site internet, c’est là encore notre première préoccupation. Pour répondre toujours mieux à vos besoins, et vous offrir une navigation simplifiée et personnalisée, nous utilisons des moyens qui nous permettent de comprendre vos besoins et vos habitudes.</p>

<p>Parmi ces moyens, les plus connus sont les « cookies ». Et nous tenions à vous expliquer le plus simplement possible comment ils fonctionnent, et répondre à vos questions.
    C’est quoi cette affaire de cookies ?</p>
On ne va pas vous faire la blague du biscuit ? (trop tard !). Un cookie, c’est un petit fichier texte déposé sur votre ordinateur, smartphone ou tablette, par nous-même ou par un tiers (partenaire, régie publicitaire…). Le cookie peut nous servir à faire fonctionner le site (cookies fonctionnels) ou à en savoir un peu plus sur vos besoins et vos habitudes, afin de vous proposer la meilleure navigation possible.
A quoi servent concrètement les cookies ? <br>
Les cookies déposés sur votre ordinateur, smartphone ou tablette nous permettent — à nous et à nos partenaires — d’améliorer votre expérience sur notre site et notre application. En clair, votre navigation sera plus simple, et les services, offres ou publicités pourront davantage coller à vos besoins et à vos habitudes. Vous voulez en savoir plus ? On vous explique tout ça ! Il suffit de distinguer quatre types de cookies. <br> <br>
<h4 class="mpy">Les cookies « techniques » ou « fonctionnels »</h4>
<div>
    Leur but est de faciliter l’accès aux services et aux rubriques de notre site. Si vous vous connectez à votre compte, cela permettra par exemple de garder votre connexion active, plutôt que de vous obliger à vous reconnecter à chaque interaction. Ces cookies-là sont obligatoires, car leur désactivation vous empêcherait de naviguer sur notre site !
</div>
Les cookies de « mesure d’audience »
<h4 class="mpy"></h4>
<div>
    Ils nous permettent de mieux comprendre comment vous naviguez. Quelles pages sont les plus consultées ? Quels sont les produits les plus commandés ? Quelle page préférez-vous lorsqu’on teste deux versions à l’aide d’un outil de test A/B ? Grâce à ces cookies, nous pouvons réaliser des statistiques, dans le but de faire évoluer notre site et notre application dans le bon sens. Mais attention : nous n’analysons jamais ces données au niveau individuel, mais uniquement au niveau global. Nous pouvons ainsi combiner vos données de navigation avec d’autres données que nous possédons, mais uniquement dans un but d’analyse globale et de suivi des tendances.
</div>

<div>
Les cookies « publicitaires » et de « personnalisation »
<h4 class="mpy"></h4>
Ce troisième type de cookies nous permet de vous proposer des offres et des publicités adaptées à vos attentes et à votre profil, sur notre site, notre application, ou chez nos partenaires, mais aussi de limiter le nombre de fois où vous verriez une même publicité. Les cookies publicitaires peuvent également être utilisés pour vous proposer nos services par téléphone, mail ou SMS. Une petite précision : le fait d’accepter les cookies publicitaires ne vous exposera pas à plus de publicités sur le web, mais vous exposera à des contenus plus pertinents.
</div>

<h4 class="mpy">Les cookies de chat et de sondages</h4>
<p>Au cours de votre navigation, certaines fonctionnalités peuvent vous être proposées afin d’améliorer votre expérience. Par exemple, nous pouvons répondre à vos questions grâce à un échange avec une conseillère ou un conseiller, ou à l’aide d’un chat bot, ou encore recueillir votre avis à l’aide d’un sondage en ligne. Ces fonctionnalités nécessitent également des traceurs afin de pouvoir vous les proposer au moment le plus adapté de votre navigation.
    </p>
